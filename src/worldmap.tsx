/** Equirectangular projection — the same one the grid is drawn on. */
export function project(lat: number, lng: number, w: number, h: number) {
  return { x: ((lng + 180) / 360) * w, y: ((90 - lat) / 180) * h };
}

const pt = (n: number) => Math.round(n * 10) / 10;

interface Pt {
  x: number;
  y: number;
}

function quad(a: Pt, c: Pt, b: Pt, t: number): Pt {
  return {
    x: (1 - t) * (1 - t) * a.x + 2 * (1 - t) * t * c.x + t * t * b.x,
    y: (1 - t) * (1 - t) * a.y + 2 * (1 - t) * t * c.y + t * t * b.y,
  };
}

/**
 * The route map, Swiss Bulletin style — the approved sample's map,
 * generalized to any width. Flat black dots (Antarctica omitted —
 * confident white space, as in print atlases), one solid red arc
 * Bengaluru → Lagos, black ring markers with crosshair ticks: the home
 * marker's centre is black, the threat marker's centre is red. The frame
 * is a hard 2px black rule. All geometry scales from the 948-wide
 * reference in samples/swiss-poster.tsx, and both cities are positioned
 * by projecting their real lat/lon.
 */
export function SwissMap({ width = 948 }: { width?: number }) {
  const w = width;
  const fullH = w / 2;
  const s = w / 948; // scale against the approved sample's geometry
  const cell = w / MAP_COLS;
  const dotR = 2.3 * s;

  const dots: Pt[] = [];
  for (let r = 0; r < MAP_ROWS; r++) {
    if (r >= 44) continue; // Antarctica omitted — confident white space
    const row = LAND_GRID[r];
    for (let c = 0; c < MAP_COLS; c++) {
      if (row[c] === "#") dots.push({ x: (c + 0.5) * cell, y: (r + 0.5) * (fullH / MAP_ROWS) });
    }
  }

  const home = project(cities.bengaluru.lat, cities.bengaluru.lng, w, fullH);
  const threat = project(cities.lagos.lat, cities.lagos.lng, w, fullH);

  const dist = Math.hypot(threat.x - home.x, threat.y - home.y);
  const ctrl = { x: (home.x + threat.x) / 2, y: (home.y + threat.y) / 2 - dist * 0.22 };
  const STEPS = 56;
  const arcPts: Pt[] = [];
  for (let i = 0; i <= STEPS; i++) arcPts.push(quad(home, ctrl, threat, i / STEPS));
  const arcSegs = arcPts.slice(0, -1).map((p, i) => ({ a: p, b: arcPts[i + 1] }));

  const marker = (c: Pt, centreFill: string) => (
    <>
      <Circle cx={pt(c.x)} cy={pt(c.y)} r={pt(10 * s)} style={{ fill: palette.paper, stroke: palette.ink, strokeWidth: 2.5 * s }} />
      <Circle cx={pt(c.x)} cy={pt(c.y)} r={pt(4.5 * s)} style={{ fill: centreFill }} />
      <Line x1={pt(c.x - 21 * s)} y1={pt(c.y)} x2={pt(c.x - 14 * s)} y2={pt(c.y)} style={{ stroke: palette.ink, strokeWidth: 2.5 * s }} />
      <Line x1={pt(c.x + 14 * s)} y1={pt(c.y)} x2={pt(c.x + 21 * s)} y2={pt(c.y)} style={{ stroke: palette.ink, strokeWidth: 2.5 * s }} />
      <Line x1={pt(c.x)} y1={pt(c.y - 21 * s)} x2={pt(c.x)} y2={pt(c.y - 14 * s)} style={{ stroke: palette.ink, strokeWidth: 2.5 * s }} />
      <Line x1={pt(c.x)} y1={pt(c.y + 14 * s)} x2={pt(c.x)} y2={pt(c.y + 21 * s)} style={{ stroke: palette.ink, strokeWidth: 2.5 * s }} />
    </>
  );

  // The sample's crop: the frame shows the inhabited world, not the
  // poles — viewBox starts 16/474 down the full height and runs 316/474.
  const cropY = fullH * (16 / 474);
  const cropH = fullH * (316 / 474);

  return (
    <Svg
      width={w}
      height={Math.round(cropH)}
      viewBox={`0 ${pt(cropY)} ${w} ${pt(cropH)}`}
      title="Route map — Bengaluru to Lagos"
      style={{ border: { width: 2, style: "solid", color: palette.ink } }}
    >
      {dots.map((d, i) => (
        <Circle key={i} cx={pt(d.x)} cy={pt(d.y)} r={pt(dotR)} style={{ fill: palette.ink }} />
      ))}
      {arcSegs.map((seg, i) => (
        <Line
          key={`a${i}`}
          x1={pt(seg.a.x)}
          y1={pt(seg.a.y)}
          x2={pt(seg.b.x)}
          y2={pt(seg.b.y)}
          style={{ stroke: palette.red, strokeWidth: 3.2 * s }}
        />
      ))}
      {marker(home, palette.ink)}
      {marker(threat, palette.red)}
    </Svg>
  );
}
